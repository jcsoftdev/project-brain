import { describe, it, expect } from "bun:test";
import { isNonCodePrompt, isTrivialPrompt } from "../../src/commands/trivial-prompt.js";

describe("isTrivialPrompt", () => {
  describe("pure acknowledgement / continuation, any length", () => {
    const cases = [
      "si",
      "yes",
      "dale",
      "ok",
      "no entendi",
      "you sure?",
      "continue",
      "thanks",
      "gracias",
      "perfect",
      "sigue",
      "listo",
      "ok gracias perfecto",
      "yes all",
      "yes yes yes",
      "gracias gracias gracias",
      "ok ok continue",
      "sale pues ok",
    ];

    for (const prompt of cases) {
      it(`"${prompt}" is trivial`, () => {
        expect(isTrivialPrompt(prompt)).toBe(true);
      });
    }
  });

  describe("carries a real code question, however short", () => {
    const cases = [
      "how does the search hook work",
      "explain the sync pipeline",
      "why is chunking slow",
      "thanks so much for the fix",
      "yes please continue with the refactor",
      "okf audit",
      "explain reindex",
      "sync bug",
      "reindex",
    ];

    for (const prompt of cases) {
      it(`"${prompt}" is not trivial`, () => {
        expect(isTrivialPrompt(prompt)).toBe(false);
      });
    }
  });

  describe("code identifier exception overrides short-prompt rule", () => {
    const cases = [
      "fix `runSync`",
      "check user_id",
      "look at handleSearch",
      "src/commands/search.ts",
      "why does src/tools/health.ts fail",
    ];

    for (const prompt of cases) {
      it(`"${prompt}" is not trivial`, () => {
        expect(isTrivialPrompt(prompt)).toBe(false);
      });
    }
  });

  describe("edge cases", () => {
    it("empty string is trivial", () => {
      expect(isTrivialPrompt("")).toBe(true);
    });

    it("whitespace-only string is trivial", () => {
      expect(isTrivialPrompt("   ")).toBe(true);
    });

    it("punctuation-only string is trivial", () => {
      expect(isTrivialPrompt("?!.")).toBe(true);
    });
  });
});

describe("isNonCodePrompt (search hook gate)", () => {
  const skip = [
    "ok, commit",
    "commit y push",
    "ok gracias, commit y push",
    "dale, continúa",
    "go on",
    "sí",
    "thanks",
    "/clear",
    "/compact keep the plan",
    "<command-name>/model</command-name>",
    "<task-notification><task-id>abc</task-id></task-notification>",
    "Caveat: The messages below were generated by the user while running local commands.",
    "Report from agent:\n  - edited a.ts\n  - edited b.ts\n  - ran tests\n  - all green",
    "fix this",
    "qué tal",
  ];
  const search = [
    "how does the search hook work",
    "explica cómo funciona el pipeline de sync",
    "why is chunking slow",
    "fix `runSync`",
    "look at handleSearch",
    "check src/tools/health.ts",
    "/Users/me/project/src/app.ts is failing",
    "yes please continue with the refactor of the store",
  ];

  for (const p of skip) it(`skips ${JSON.stringify(p)}`, () => expect(isNonCodePrompt(p)).toBe(true));
  for (const p of search) it(`searches ${JSON.stringify(p)}`, () => expect(isNonCodePrompt(p)).toBe(false));

  it("keeps isTrivialPrompt unchanged for short real questions (shared with suggest)", () => {
    expect(isTrivialPrompt("sync bug")).toBe(false);
    expect(isNonCodePrompt("sync bug")).toBe(true);
  });
});
